export function TeamGlyph({ teamKey, size = 14 }: { teamKey: string; size?: number }) {
  if (teamKey === "BACKEND") return <IconServer size={size} />;
  if (teamKey === "NETWORK") return <IconNetwork size={size} />;
  if (teamKey === "CONTENT") return <IconFile size={size} />;
  if (teamKey === "SEO") return <IconSearch size={size} />;
  return <IconCode size={size} />;
}

export function navIcon(href: string, size = 18, strokeWidth = 1.8) {
  const p = { size, strokeWidth };
  if (href === "/my-checks") return <IconChecks {...p} />;
  if (href === "/projects") return <IconFolder {...p} />;
  if (href === "/reviews") return <IconStamp {...p} />;
  if (href === "/templates") return <IconBook {...p} />;
  if (href === "/admin") return <IconUsers {...p} />;
  if (href === "/management") return <IconBriefcase {...p} />;
  return <IconDashboard {...p} />;
}
